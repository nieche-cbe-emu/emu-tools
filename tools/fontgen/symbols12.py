def cell(ch):
    lines = [l for l in GLYPHS[ch].split("\n")[1:-1]]
    lines += ["." * 12] * (12 - len(lines))
    out = []
    for l in lines[:12]:
        l = (l + "." * 12)[:12]
        out.append(sum(1 << (11 - i) for i, c in enumerate(l) if c == "#"))
    return out
